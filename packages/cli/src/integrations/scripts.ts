import os from "node:os";

export interface StartupScriptInput {
  /** 启动脚本用来找 Node 的候选路径（真实路径优先） */
  nodeCandidates: string[];
  cliPath: string;
  /** 当前用户主目录（默认 os.homedir()，测试里可覆盖） */
  home?: string;
  appData?: string;
  localAppData?: string;
}

/**
 * Windows cmd 按系统代码页（如 GBK）读取 .cmd，因此脚本里尽量不写中文字面路径：
 * 能用 %USERPROFILE% / %APPDATA% / %LOCALAPPDATA% 表示的都用环境变量。
 */
function envifyWindowsPath(p: string, input: StartupScriptInput): string {
  const rules: Array<[string | undefined, string]> = [
    [input.localAppData ?? process.env["LOCALAPPDATA"], "%LOCALAPPDATA%"],
    [input.appData ?? process.env["APPDATA"], "%APPDATA%"],
    [input.home ?? os.homedir(), "%USERPROFILE%"],
  ];
  for (const [prefix, token] of rules) {
    if (!prefix) continue;
    if (p === prefix) return token;
    if (p.toLowerCase().startsWith((prefix + "\\").toLowerCase())) {
      return token + p.slice(prefix.length);
    }
  }
  return p;
}

/**
 * 启动脚本里的 Node 版本闸门：低于 engines 要求（>=22.16）的候选直接跳过。
 * nvm 等版本管理器切换后，"当前版本"路径会指向别的 Node（可能过旧，
 * 缺 node:sqlite 会让 CLI 一启动就崩）——只按"文件存在"选会静默把 hook 跑挂。
 */
const VERSION_CHECK =
  "const v=process.versions.node.split('.').map(Number);process.exit(v[0]>22||(v[0]===22&&v[1]>=15)?0:1)";

/**
 * POSIX sh 启动脚本。按候选顺序试 Node（每个候选先过版本闸门），最后回退 PATH。
 * 全部失败时提示重新运行 npm i -g memrelay && memrelay setup。
 */
export function renderSh(input: StartupScriptInput): string {
  const candidates = input.nodeCandidates
    .map(
      (p) =>
        `if [ -x "${p}" ] && "${p}" -e "${VERSION_CHECK}" 2>/dev/null; then exec "${p}" "${input.cliPath}" "$@"; fi`,
    )
    .join("\n");
  return `#!/bin/sh
# MemRelay launcher (generated by memrelay setup; safe to delete)
${candidates}
if command -v node >/dev/null 2>&1 && node -e "${VERSION_CHECK}" 2>/dev/null; then exec node "${input.cliPath}" "$@"; fi
echo "MemRelay: no usable Node found. Run: npm i -g memrelay && memrelay setup" >&2
exit 2
`;
}

/**
 * Windows cmd 启动脚本。脚本里不写中文字面路径，能用环境变量的一律用环境变量。
 * 版本闸门与 sh 相同；退出码用 `if errorlevel N` 级联传递（块内 %ERRORLEVEL% 会拿到解析期旧值）。
 */
export function renderCmd(input: StartupScriptInput): string {
  const cli = envifyWindowsPath(input.cliPath, input);
  const candidates = input.nodeCandidates
    .map((p) => envifyWindowsPath(p, input))
    .map(
      (p) =>
        `if exist "${p}" (\n` +
        `  "${p}" -e "${VERSION_CHECK}" >nul 2>nul\n` +
        `  if not errorlevel 1 (\n` +
        `    "${p}" "${cli}" %*\n` +
        `    if errorlevel 2 exit /b 2\n` +
        `    if errorlevel 1 exit /b 1\n` +
        `    exit /b 0\n` +
        `  )\n` +
        `)`,
    )
    .join("\n");
  return `@echo off
rem MemRelay launcher (generated by memrelay setup; safe to delete)
${candidates}
where node >nul 2>nul
if not errorlevel 1 (
  node -e "${VERSION_CHECK}" >nul 2>nul
  if not errorlevel 1 (
    node "${cli}" %*
    if errorlevel 2 exit /b 2
    if errorlevel 1 exit /b 1
    exit /b 0
  )
)
echo MemRelay: no usable Node found. Run: npm i -g memrelay ^&^& memrelay setup 1>&2
exit /b 2
`;
}
